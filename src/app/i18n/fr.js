// Typographie : les espaces avant « : ; ? ! » et à l'intérieur des guillemets sont rendues insécables par fixPunct().
const NBSP = ' ', NNBSP = ' ';
function fixPunct(v) {
  if (typeof v === 'string') {
    return v.replace(/ :/g, NBSP + ':').replace(/ ([;?!])/g, NNBSP + '$1').replace(/« /g, '«' + NBSP).replace(/ »/g, NBSP + '»');
  }
  if (Array.isArray(v)) return v.map(fixPunct);
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, fixPunct(x)]));
  return v;
}

